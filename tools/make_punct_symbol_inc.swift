// Writes src/punct_symbol.inc: the ranges of code points from U+0080 up in the
// Unicode P (punctuation) and S (symbol) general categories, which CommonMark
// 0.31 calls Unicode punctuation. It reads the Unicode data of the Swift
// standard library that runs it, so the Unicode version is that of the
// toolchain; the output names it.
//
//   swift tools/make_punct_symbol_inc.swift > src/punct_symbol.inc

let categories: Set<Unicode.GeneralCategory> = [
  .connectorPunctuation, .dashPunctuation, .openPunctuation, .closePunctuation,
  .initialPunctuation, .finalPunctuation, .otherPunctuation,
  .mathSymbol, .currencySymbol, .modifierSymbol, .otherSymbol,
]

var version = (0, 0)
var ranges: [(UInt32, UInt32)] = []
for value in UInt32(0x80) ... 0x10FFFF {
  guard let scalar = Unicode.Scalar(value) else { continue }
  if let age = scalar.properties.age, (age.major, age.minor) > version {
    version = (age.major, age.minor)
  }
  guard categories.contains(scalar.properties.generalCategory) else { continue }
  if let last = ranges.last, last.1 + 1 == value {
    ranges[ranges.count - 1].1 = value
  } else {
    ranges.append((value, value))
  }
}

func hex(_ value: UInt32) -> String {
  "0x" + String(value, radix: 16, uppercase: true)
}

print("// Generated by tools/make_punct_symbol_inc.swift from Unicode \(version.0).\(version.1).")
print("// Code points from U+0080 up in the P and S general categories.")
print("")
print("static const uint32_t ps_ranges[][2] = {")
for range in ranges {
  print("  {\(hex(range.0)), \(hex(range.1))},")
}
print("};")
print("")
print("#define PS_RANGES_SIZE (sizeof(ps_ranges) / sizeof(ps_ranges[0]))")
